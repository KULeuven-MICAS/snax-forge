def _serial_movers(tmp_path) -> dict[str, list[dict]]:
    """dot_serial's two sets' movers (csrs.movers of each set's template), by set."""
    p = DesignPoint.load(
        point(tmp_path, name="dot_serial", graph=bound_recipe("dot_serial", "dot"))
    )
    return {a: movers(streamer_template(p, mine)) for a, mine in units(p).items()}


@pytest.mark.parametrize(("ours", "first", "theirs"), [("mul", 960, "vmul"), ("sum", 982, "vsum")])
def test_a_sets_header_is_snax_clusters_byte_for_byte(tmp_path, ours, first, theirs):
    """snax_cluster ry/slot1's StreamerSwHeaderGen with the same --csr-base, --macro-prefix and
    --header-name writes the same bytes, its timestamp line aside (snax-forge-sw compares them,
    C§18)."""
    by_set = _serial_movers(tmp_path)
    text, _ = streamer_header(
        by_set[ours], first, f"{theirs.upper()}_", "out/design/x/design_point.json"
    )
    want = (SNAX_CLUSTER / f"streamer_{theirs}_csr_addr_map.h").read_text().splitlines(True)
    got = text.splitlines(True)
    assert want[6].startswith("// Generated at ") and got[6].startswith(
        "// Generated by snax-forge"
    )
    assert got[:6] + got[7:] == want[:6] + want[7:]


def test_dot_serials_headers_are_c16s_table(tmp_path):
    """dot_serial, two sets (D157, C§16's table): mul's streamer 960-977 and own CSRs 978-981, sum's
    982-994 and 995-999; each set's header its own prefix, each accelerator's its own names."""
    from .helpers import designed

    path = designed(tmp_path, "dot_serial", "dot_serial")
    m = generate(tmp_path / path, tmp_path / "gen", root=tmp_path)
    inc = tmp_path / "gen" / "include"
    assert [f for f in m.files if f.startswith("include/")][:4] == [
        "include/streamer_mul_csr_addr_map.h", "include/mul_csr.h",
        "include/streamer_sum_csr_addr_map.h", "include/sum_csr.h",
    ]  # fmt: skip
    mul_s = defines((inc / "streamer_mul_csr_addr_map.h").read_text())
    sum_s = defines((inc / "streamer_sum_csr_addr_map.h").read_text())
    assert mul_s == [(f"MUL_{k}", v) for k, v in STREAMER_W4]  # vecadd's shape
    assert (sum_s[0], sum_s[-3:]) == (("SUM_BASE_PTR_READER_0_LOW", 982), [
        ("SUM_STREAMER_START_CSR", 992), ("SUM_STREAMER_BUSY_CSR", 993),
        ("SUM_STREAMER_PERFORMANCE_COUNTER_CSR", 994)])  # fmt: skip
    assert defines((inc / "mul_csr.h").read_text()) == [
        ("MUL_RW_START", 978), ("MUL_RW_JOBS", 979), ("MUL_RO_STATUS", 980), ("MUL_RO_BUSY_COUNTER", 981)
    ]  # fmt: skip
    assert defines((inc / "sum_csr.h").read_text()) == [
        ("SUM_RW_START", 995), ("SUM_RW_JOBS", 996), ("SUM_RW_JOB_BEATS", 997),
        ("SUM_RO_STATUS", 998), ("SUM_RO_BUSY_COUNTER", 999),
    ]  # fmt: skip
    assert m.csrs.to_dict() == {
        "streamers": [
            {"name": "mul", "first": 960, "last": 977, "trace": "snax_acc0/streamer_mul"},
            {"name": "sum", "first": 982, "last": 994, "trace": "snax_acc0/streamer_sum"},
        ],
        "accelerator": dict(defines((inc / "mul_csr.h").read_text())
                            + defines((inc / "sum_csr.h").read_text())),
    }  # fmt: skip


