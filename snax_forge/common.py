"""What every package shares: the repository root and the JSON form of every artefact.

* ``repo_root``, the directory holding ``pixi.toml``: where ``out/``, ``kernels/`` and the
  platforms are found; ``cwd_relative``, a path as a command line prints it;
  ``generated_header``, the comment every generated file starts with; ``fresh`` and
  ``unique_names``, names that clash with none taken before; ``git``, a git command's output
  in a folder, or None; ``dig``, the value at a dotted path of nested objects;
  ``write_changed``, a file written only when its text changes.
* ``CodedError``, the base of the refusals that carry a rule code; ``LoadedSet``, what a
  viewer serves, reloaded whole.
* ``plain`` and ``check_keys``: JSON-ready values, and an object's unknown keys refused (so a
  typo never silently falls back to a default) and its required ones checked.
* ``Config``, a mixin giving a flat dataclass ``to_dict`` / ``from_dict``. Every field is
  written, defaults included, so a written file says everything and a missing key takes the
  class default.
* ``to_json``, the one JSON writer for every file snax-forge writes: insertion order, small
  containers on one line, final newline. It is deterministic, and ``json.loads`` gives the
  object back (D44). ``JsonFile``, a mixin giving a class with ``to_dict`` / ``from_dict``
  its ``to_json``, ``save`` and ``load``.

Until the contracts freeze these are plain dataclasses and plain JSON, with versioned schemas
after (D26). This module imports nothing from the package, so every package can use it.
"""

from __future__ import annotations

import json
import subprocess
import textwrap
import threading
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import fields
from pathlib import Path
from typing import Any

# =============================================================================
# The repository
# =============================================================================


def repo_root() -> Path:
    """The directory holding pixi.toml, found by walking up from this module, so it does not
    depend on how deep the module sits."""
    for parent in Path(__file__).resolve().parents:
        if (parent / "pixi.toml").is_file():
            return parent
    raise RuntimeError(f"no pixi.toml found above {Path(__file__).resolve()}")


# The width of a generated file's header comment, after "// "
HEADER_WIDTH = 77


def generated_header(point_path: str, what: str) -> str:
    """The comment every file the generator writes starts with (hjson, headers, data.h,
    main.c): the generator, the design point by its path from the root, the command that
    writes it again, then what the file is; ``//`` lines, which C and hjson read."""
    wrap = {"width": HEADER_WIDTH, "break_long_words": False, "break_on_hyphens": False}
    lines = textwrap.wrap(
        f"Generated by snax-forge's generator (snax_forge/gen) from the design point "
        f"{point_path}. Do not edit: run `pixi run gen-gvsoc {point_path}` again.",
        **wrap,
    )
    lines += textwrap.wrap(what, **wrap)
    return "".join(f"// {line}\n" for line in lines)


class Missing(LookupError):
    """``dig``'s: key ``at`` (an index into the dotted path) is not there; ``in_object`` False
    when what it was looked up in is not an object. Each caller words its own error."""

    def __init__(self, at: int, in_object: bool):
        super().__init__(at, in_object)
        self.at, self.in_object = at, in_object


def dig(d: Any, path: str) -> Any:
    """The value at the dotted ``path`` of ``d``: a key of ``d``, then of its value, and so on;
    ``Missing`` at the first key that is not there."""
    node = d
    for i, key in enumerate(path.split(".")):
        if not isinstance(node, Mapping):
            raise Missing(i, False)
        if key not in node:
            raise Missing(i, True)
        node = node[key]
    return node


def write_changed(path: Path, text: str) -> bool:
    """Write ``text`` to ``path`` unless it holds it already: an unchanged file keeps its
    mtime, so what make builds from it is not rebuilt. Whether it wrote."""
    if path.is_file() and path.read_text() == text:
        return False
    path.write_text(text)
    return True


def git(path: Path, *args: str) -> str | None:
    """git's stdout in ``path``, stripped, or None when git fails or is missing. With
    ``safe.directory=*``: in the image, git may not own the mounted folder."""
    try:
        r = subprocess.run(["git", "-c", "safe.directory=*", "-C", str(path), *args],
                           capture_output=True, text=True, check=False)  # fmt: skip
    except OSError:
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def cwd_relative(p: Path) -> str:
    """``p`` as a command line prints it: relative to the working directory when inside it."""
    try:
        return str(p.resolve().relative_to(Path.cwd()))
    except ValueError:
        return str(p)


def fresh(base: str, taken: set[str]) -> str:
    """``base``, or ``base_1``, ``base_2``, ... whichever is not taken; the result is taken."""
    name, k = base, 0
    while name in taken:
        k += 1
        name = f"{base}_{k}"
    taken.add(name)
    return name


def unique_names(bases: Iterable[str]) -> list[str]:
    """Each base, made unique with -2, -3, ... in the order given."""
    names: list[str] = []
    for base in bases:
        name, i = base, 1
        while name in names:
            i += 1
            name = f"{base}-{i}"
        names.append(name)
    return names


