"""What every package shares: the repository root and the JSON form of every artefact.

* ``repo_root``, the directory holding ``pixi.toml``: where ``out/``, ``kernels/`` and the
  platforms are found; ``cwd_relative``, a path as a command line prints it;
  ``generated_header``, the comment every generated file starts with; ``fresh`` and
  ``unique_names``, names that clash with none taken before.
* ``CodedError``, the base of the refusals that carry a rule code.
* ``plain`` and ``check_keys``: JSON-ready values, and an object's unknown keys refused (so a
  typo never silently falls back to a default) and its required ones checked.
* ``Config``, a mixin giving a flat dataclass ``to_dict`` / ``from_dict``. Every field is
  written, defaults included, so a written file says everything and a missing key takes the
  class default.
* ``to_json``, the one JSON writer for every file snax-forge writes: insertion order, small
  containers on one line, final newline. It is deterministic, and ``json.loads`` gives the
  object back (D44). ``JsonFile``, a mixin giving a class with ``to_dict`` / ``from_dict``
  its ``to_json``, ``save`` and ``load``.

Until the contracts freeze these are plain dataclasses and plain JSON, with versioned schemas
after (D26). This module imports nothing from the package, so every package can use it.
"""

from __future__ import annotations

import json
import textwrap
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import fields
from pathlib import Path
from typing import Any

# =============================================================================
# The repository
# =============================================================================


def repo_root() -> Path:
    """The directory holding pixi.toml, found by walking up from this module, so it does not
    depend on how deep the module sits."""
    for parent in Path(__file__).resolve().parents:
        if (parent / "pixi.toml").is_file():
            return parent
    raise RuntimeError(f"no pixi.toml found above {Path(__file__).resolve()}")


# The width of a generated file's header comment, after "// "
HEADER_WIDTH = 77


def generated_header(point_path: str, what: str) -> str:
    """The comment every file the generator writes starts with (hjson, headers, data.h,
    main.c): the generator, the design point by its path from the root, the command that
    writes it again, then what the file is; ``//`` lines, which C and hjson read."""
    wrap = {"width": HEADER_WIDTH, "break_long_words": False, "break_on_hyphens": False}
    lines = textwrap.wrap(
        f"Generated by snax-forge's generator (snax_forge/gen) from the design point "
        f"{point_path}. Do not edit: run `pixi run gen-gvsoc {point_path}` again.",
        **wrap,
    )
    lines += textwrap.wrap(what, **wrap)
    return "".join(f"// {line}\n" for line in lines)


def cwd_relative(p: Path) -> str:
    """``p`` as a command line prints it: relative to the working directory when inside it."""
    try:
        return str(p.resolve().relative_to(Path.cwd()))
    except ValueError:
        return str(p)


def fresh(base: str, taken: set[str]) -> str:
    """``base``, or ``base_1``, ``base_2``, ... whichever is not taken; the result is taken."""
    name, k = base, 0
    while name in taken:
        k += 1
        name = f"{base}_{k}"
    taken.add(name)
    return name


def unique_names(bases: Iterable[str]) -> list[str]:
    """Each base, made unique with -2, -3, ... in the order given."""
    names: list[str] = []
    for base in bases:
        name, i = base, 1
        while name in names:
            i += 1
            name = f"{base}-{i}"
        names.append(name)
    return names


# =============================================================================
# Plain values and key checks
# =============================================================================


def plain(v: Any) -> Any:
    """Tuples -> lists, mappings -> dicts, recursively: JSON-ready values."""
    if isinstance(v, Mapping):
        return {k: plain(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [plain(x) for x in v]
    return v


def check_keys(
    d: Any, allowed: Sequence[str], what: str = "", required: Sequence[str] = (),
    noun: str = "key",
) -> None:  # fmt: skip
    """``d`` is an object (else TypeError) with no key outside ``allowed`` and every one of
    ``required`` (else ValueError, naming the first missing ``noun``). ``what`` prefixes the
    message when it is given; a caller re-raises in its own error class."""
    head = f"{what}: " if what else ""
    if not isinstance(d, Mapping):
        raise TypeError(f"{head}must be an object, got {d!r}")
    unknown = sorted(set(d) - set(allowed))
    if unknown:
        raise ValueError(f"{head}unknown keys {unknown} (allowed: {list(allowed)})")
    missing = [k for k in required if k not in d]
    if missing:
        raise ValueError(f"{head}missing {noun} {missing[0]!r}")


class CodedError(ValueError):
    """A refusal whose ``code`` names the rule (``<module>.<rule>``), shown first in the message.
    Each package subclasses it so callers catch its own refusals."""

    def __init__(self, code: str, message: str) -> None:
        self.code = code
        super().__init__(f"[{code}] {message}")


# =============================================================================
# The mixin
# =============================================================================


class Config:
    """Flat dataclass <-> plain dict. Mixed into every config class."""

    def to_dict(self) -> dict[str, Any]:
        """Every field, in declaration order, as JSON-ready values."""
        return {f.name: plain(getattr(self, f.name)) for f in fields(self)}

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> Any:
        """Inverse of ``to_dict``; missing keys take the class default.

        Raises ValueError for unknown keys and for values the class itself
        rejects.
        """
        check_keys(d, [f.name for f in fields(cls)])
        return cls(**d)


# =============================================================================
# JSON writing
# =============================================================================

JSON_WIDTH = 100  # line length of written JSON, as ruff's for the code


def _scalar(v: Any) -> bool:
    return not isinstance(v, (dict, list, tuple))


def _json(v: Any, indent: int, col: int) -> str:
    """One value, its block indented by ``indent``, starting at column ``col``.

    A container goes on one line if it ends within JSON_WIDTH, and a list of
    scalars always does (a histogram stays one line); otherwise one item per
    line, one space deeper.
    """
    flat = json.dumps(v)
    if _scalar(v) or (isinstance(v, (list, tuple)) and all(map(_scalar, v))):
        return flat
    if col + len(flat) <= JSON_WIDTH or not v:
        return flat
    pad = " " * (indent + 1)
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            head = f"{pad}{json.dumps(k)}: "
            items.append(head + _json(x, indent + 1, len(head)))
        return "{\n" + ",\n".join(items) + "\n" + " " * indent + "}"
    items = [pad + _json(x, indent + 1, len(pad)) for x in v]
    return "[\n" + ",\n".join(items) + "\n" + " " * indent + "]"


def to_json(obj: Any) -> str:
    """The one JSON format of every written file."""
    return _json(obj, 0, 0) + "\n"


class JsonFile:
    """``to_json``, ``save`` and ``load`` for a class with ``to_dict`` and ``from_dict``."""

    def to_json(self) -> str:
        return to_json(self.to_dict())  # type: ignore[attr-defined]

    def save(self, path: str | Path) -> None:
        Path(path).write_text(self.to_json())

    @classmethod
    def load(cls, path: str | Path) -> Any:
        return cls.from_dict(json.loads(Path(path).read_text()))  # type: ignore[attr-defined]
